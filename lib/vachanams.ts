const CATEGORY_ORDER: CategoryId[] = [
  'karma',
  'dharma',
  'bhakti',
  'love',
  'peace',
  'wisdom',
  'courage',
  'forgiveness',
  'life',
]

const TARGET_TOTAL = 2400

/** Small deterministic PRNG so the generated set is identical on every load. */
function mulberry32(seed: number) {
  return function () {
    seed |= 0
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function shuffle<T>(arr: T[], rand: () => number): T[] {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
    ;[arr[i], arr[j]] = [arr[j], arr[i]]
  }
  return arr
}

function build(): Vachanam[] {
  const rand = mulberry32(20240815)
  const collected: { text: string; category: CategoryId }[] = []

  CATEGORY_ORDER.forEach((category, index) => {
    const { subjects, predicates } = source[category]
    const combos: string[] = []
    for (const subject of subjects) {
      for (const predicate of predicates) {
        combos.push(`${subject} ${predicate}`)
      }
    }
    const unique = shuffle(Array.from(new Set(combos)), rand)
    // Distribute 2400 as evenly as possible across the 9 categories.
    const quota = index < TARGET_TOTAL % CATEGORY_ORDER.length
      ? Math.ceil(TARGET_TOTAL / CATEGORY_ORDER.length)
      : Math.floor(TARGET_TOTAL / CATEGORY_ORDER.length)
    for (const text of unique.slice(0, quota)) {
      collected.push({ text, category })
    }
  })

  return shuffle(collected, rand).map((item, idx) => ({
    id: idx + 1,
    text: item.text,
    category: item.category,
  }))
}

export const vachanams: Vachanam[] = build()
export const TOTAL_VACHANAMS = vachanams.length
